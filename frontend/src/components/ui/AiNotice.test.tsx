import { render, screen } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import { AiNotice } from './AiNotice';

describe('AiNotice', () => {
  it('shows the AI badge and default disclosure', () => {
    render(<AiNotice />);
    expect(screen.getByText('AI')).toBeInTheDocument();
    expect(screen.getByRole('note')).toHaveTextContent('行程由 AI 生成');
    expect(screen.getByRole('note')).toHaveTextContent('出发前核实');
  });

  it('renders custom copy for shared pages', () => {
    render(<AiNotice>Itinerary generated by AI.</AiNotice>);
    expect(screen.getByRole('note')).toHaveTextContent('Itinerary generated by AI.');
  });
});
